import fs from 'node:fs';
import assert from 'node:assert/strict';
import {LEARNING_STAGES,CHAPTER_DESTINATIONS,buildLearningPath} from '../learning-path.js';
const {chapters,lessons}=JSON.parse(fs.readFileSync(new URL('../content.json',import.meta.url),'utf8'));
assert.deepEqual(LEARNING_STAGES.flatMap(stage=>stage.chapters),chapters.map(c=>c.id),'Each chapter belongs to one stage, in book order');
for(const c of chapters)assert.ok(CHAPTER_DESTINATIONS[c.id].every(label=>label.length>0));
const fresh=buildLearningPath(chapters,lessons,[],null);
assert.equal(fresh.next.id,chapters[0].sectionIds[0]);
assert.equal(fresh.last,null);
assert.equal(fresh.total,195);
const first=chapters[0],second=chapters[1];
const partial=buildLearningPath(chapters,lessons,[...first.sectionIds,second.sectionIds[0],first.sectionIds[0],'obsolete-id'],lessons.at(-1).id);
assert.equal(partial.readCount,first.sectionIds.length+1,'Duplicate and stale records do not inflate progress');
assert.equal(partial.next.id,second.sectionIds[1]);
assert.equal(partial.last.id,lessons.at(-1).id,'Last opened and recommended next remain distinct');
assert.equal(partial.stages[0].items[0].complete,true);
assert.equal(partial.stages[0].items[1].nextId,second.sectionIds[1]);
const later=buildLearningPath(chapters,lessons,LEARNING_STAGES[0].chapters.flatMap(id=>chapters.find(c=>c.id===id).sectionIds),'missing-id');
assert.equal(later.next.chapter,4);
assert.equal(later.stages[0].readCount,later.stages[0].total);
assert.equal(later.last,null);
const finished=buildLearningPath(chapters,lessons,lessons.map(l=>l.id),null);
assert.equal(finished.next,null,'A complete route offers review instead of an invalid lesson');
assert.equal(finished.readCount,195);
assert.ok(finished.stages.every(stage=>stage.readCount===stage.total));
assert.ok(finished.stages.flatMap(s=>s.items).every(c=>c.nextId===c.sectionIds[0]));
console.log('PASS: all 20 chapters mapped once; next unread, partial/completed stages, stale/duplicate records and all-read review routing.');
